// Measures where each interface icon actually draws, so tiles can centre and size
// icons by their visible ink instead of by the SVG box.
// Writes .local/materials/metrics.js; copy it to app/assets/icons/ after review.
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { openPreview, root } from '../lib/browser.mjs';

const RASTER = 240,
  INK_ALPHA = 40;
const names = readdirSync(root + 'app/assets/icons')
  .filter(f => f.endsWith('.svg'))
  .map(f => f.replace(/\.svg$/, ''));

/* Runs in the page: rasterises one SVG and returns its ink box and density. */
async function measure({ name, size, threshold }) {
  const text = await fetch('/home/assets/icons/' + name + '.svg').then(r => r.text());
  const doc = new DOMParser().parseFromString(text, 'image/svg+xml').documentElement;
  doc.setAttribute('width', size);
  doc.setAttribute('height', size);
  doc.setAttribute('preserveAspectRatio', 'xMidYMid meet');
  const blob = new Blob([new XMLSerializer().serializeToString(doc)], { type: 'image/svg+xml' });
  const src = URL.createObjectURL(blob);
  const img = new Image();
  img.src = src;
  await img.decode();
  URL.revokeObjectURL(src);

  const ctx = Object.assign(document.createElement('canvas'), {
    width: size,
    height: size
  }).getContext('2d');
  ctx.drawImage(img, 0, 0, size, size);
  const alpha = ctx.getImageData(0, 0, size, size).data;
  const box = { x0: size, y0: size, x1: -1, y1: -1 };
  let coverage = 0;
  for (let i = 3, p = 0; i < alpha.length; i += 4, p++) {
    coverage += alpha[i] / 255;
    if (alpha[i] <= threshold) continue;
    const x = p % size,
      y = (p - x) / size;
    if (x < box.x0) box.x0 = x;
    if (x > box.x1) box.x1 = x;
    if (y < box.y0) box.y0 = y;
    if (y > box.y1) box.y1 = y;
  }
  if (box.x1 < 0) throw new Error('Icon draws nothing: ' + name);
  const w = box.x1 - box.x0 + 1,
    h = box.y1 - box.y0 + 1;
  return { n: size, x: box.x0, y: box.y0, w, h, fill: coverage / (w * h) };
}

const preview = await openPreview();
try {
  const page = await preview.browser.newPage();
  await page.goto(preview.baseURL + '/build/canvas.html');
  const metrics = {};
  for (const name of names)
    metrics[name] = await page.evaluate(measure, { name, size: RASTER, threshold: INK_ALPHA });
  mkdirSync(root + '.local/materials', { recursive: true });
  writeFileSync(
    root + '.local/materials/metrics.js',
    '/* Icon ink boxes, generated by scripts/build/build-icon-metrics.mjs. */\nwindow.ZenoIconMetrics = ' +
      JSON.stringify(metrics, null, 2) +
      ';\n'
  );
  console.log(names.length + ' icons measured → .local/materials/metrics.js');
} finally {
  await preview.close();
}
